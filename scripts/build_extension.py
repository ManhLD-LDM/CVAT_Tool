"""
Build script for CVAT 3D Tool Extension.
Combines modular source files into standalone MAIN and ISOLATED world scripts:
- copilot_main.js  <- geometry_math.js + cvat_adapter.js + main_world_bridge.js
- copilot_panel.js <- geometry_math.js + content_script.js
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXT_DIR = ROOT / "extension"

HEADER = "/* Generated by scripts/build_extension.py. Edit source files, then rebuild. */\n"

BUNDLES = [
    ("copilot_main.js", ["geometry_math.js", "batch_math.js", "batch_cloud.js", "batch_controller.js", "cvat_adapter.js", "main_world_bridge.js"]),
    ("copilot_panel.js", ["geometry_math.js", "batch_math.js", "batch_ui.js", "session_transport.js", "shortcut_settings.js", "content_script.js"]),
]

def build():
    print("Building extension bundles...")
    for out_name, in_names in BUNDLES:
        parts = []
        for name in in_names:
            p = EXT_DIR / name
            if not p.exists():
                raise FileNotFoundError(f"Missing input file: {p}")
            parts.append(p.read_text(encoding="utf-8"))
        
        combined = HEADER + "\n;\n".join(parts) + "\n"
        out_file = EXT_DIR / out_name
        out_file.write_text(combined, encoding="utf-8")
        print(f" -> Generated: {out_file.name} ({len(combined.encode('utf-8'))} bytes)")

    print("SUCCESS: Built self-contained MAIN and ISOLATED extension scripts.")

if __name__ == "__main__":
    build()
