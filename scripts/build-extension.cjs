/* Each execution world receives its own self-contained geometry dependency.
 * Avoid retaining an undefined geometry global from a partially loaded panel.
 */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../extension');
for(const [output,inputs] of [
    ['copilot_main.js',['geometry_math.js','cvat_adapter.js','main_world_bridge.js']],
    ['copilot_panel.js',['geometry_math.js','content_script.js']],
]){
    const source='/* Generated by scripts/build-extension.cjs. Edit source files, then rebuild. */\n'+inputs.map(name=>fs.readFileSync(path.join(root,name),'utf8')).join('\n;\n');
    fs.writeFileSync(path.join(root,output),source);
}
console.log('Built self-contained MAIN and ISOLATED extension scripts.');
